#!/usr/bin/env python3
"""Rebuild versions/: one playable snapshot of every version, at versions/vN/index.html.

v7 onward come from git: the last first-parent commit on main holding each version (by the newest entry
in data/effort.js, or the "vN:" commit subject before effort.js existed). v1 to v6 were never in git; they
were rebuilt from the original chat's steps and are kept as they are (this script never touches them).
Each snapshot gets its own saved settings (localStorage keys prefixed "bhd-vN:") so playing an old
version can't change the live game's save, and a button back to the list. Run from the repo root after
a version merges to main:  python3 tools/versions.py
"""
import json, os, re, shutil, subprocess

OUT = 'versions'
SKIP = ('versions/', 'tools/', 'build.html', 'README.md', 'CLAUDE.md', '.git')
KEEP = range(1, 7)          # hand-recovered snapshots, not in git
# versions whose last first-parent commit on main is a later branch's work in progress (that branch was
# fast-forwarded onto main), pinned to the commit that shipped them
PIN = {55: '8b58bd4'}


def git(*a, text=True):
    return subprocess.run(['git', *a], capture_output=True, text=text, check=True).stdout


def version_of(sha, subject):
    try:
        e = git('show', f'{sha}:data/effort.js')
        vs = [int(x) for x in re.findall(r'"v":\s*(\d+)', e)]
        if vs:
            return max(vs)
    except subprocess.CalledProcessError:
        pass
    m = re.match(r'v(\d+):', subject)
    return int(m.group(1)) if m else None


def wrap(html, v):
    ns = ("<script>(function(){try{var P='bhd-v%d:',S=Storage.prototype,g=S.getItem,s=S.setItem,r=S.removeItem;"
          "S.getItem=function(k){return g.call(this,P+k)};S.setItem=function(k,x){return s.call(this,P+k,x)};"
          "S.removeItem=function(k){return r.call(this,P+k)}}catch(e){}})();</script>" % v)
    pill = ('<a id="verPill" href="../" aria-label="Version %d. Back to all versions">&#9664; v%d</a><style>#verPill{position:fixed;'
            'left:0;top:50%%;transform:translateY(-50%%);z-index:2147483000;padding:12px 12px 12px calc(env(safe-area-inset-left,0px) + 10px);'
            'font:800 18px/1 "Saira Condensed","Arial Narrow",sans-serif;letter-spacing:.04em;color:#1c1309;background:#f5c518;'
            'border-radius:0 12px 12px 0;text-decoration:none;box-shadow:0 3px 10px rgba(0,0,0,.35)}</style>\n' % (v, v))
    html = html.replace('<head>', '<head>\n' + ns, 1)
    i = html.rfind('</html>')
    return html[:i] + pill + html[i:] if i >= 0 else html + pill


def main():
    root = git('rev-parse', '--show-toplevel').strip()
    os.chdir(root)
    log = git('log', '--first-parent', '--reverse', '--format=%H %cI %s', 'origin/main' if
              subprocess.run(['git', 'rev-parse', '-q', '--verify', 'origin/main'], capture_output=True).returncode == 0
              else 'HEAD').splitlines()
    last = {}
    for line in log:
        sha, when, subject = line.split(' ', 2)
        v = version_of(sha, subject)
        if v:
            last[v] = (sha, when)
    # versions merged together with a later one (e.g. "v25 ..., v26 ...") never sat on main by themselves;
    # take the last branch commit that ended on that version instead
    for line in git('log', '--reverse', '--topo-order', '--format=%H %cI %s', log[-1].split(' ')[0]).splitlines():
        sha, when, subject = line.split(' ', 2)
        v = version_of(sha, subject)
        if v and (v not in last or last[v][2:]):
            last[v] = (sha, when, 'branch')
    for d in os.listdir(OUT) if os.path.isdir(OUT) else []:
        m = re.fullmatch(r'v(\d+)', d)
        if m and int(m.group(1)) not in KEEP:
            shutil.rmtree(os.path.join(OUT, d))
    for v, c in PIN.items():
        last[v] = (git('rev-parse', c).strip(), '')
    for v, (sha, when, *_) in sorted(last.items()):
        if v in KEEP:
            continue
        dest = os.path.join(OUT, f'v{v}')
        for path in git('ls-tree', '-r', '--name-only', sha).splitlines():
            if path.startswith(SKIP) or '/' in path and path.split('/')[0] not in ('js', 'css', 'data', 'shots'):
                continue
            blob = git('show', f'{sha}:{path}', text=False)
            if path == 'index.html':
                blob = wrap(blob.decode(), v).encode()
            os.makedirs(os.path.dirname(os.path.join(dest, path)) or dest, exist_ok=True)
            open(os.path.join(dest, path), 'wb').write(blob)
    have = sorted(int(d[1:]) for d in os.listdir(OUT) if re.fullmatch(r'v\d+', d))
    with open(os.path.join(OUT, 'list.js'), 'w') as f:
        f.write('// Generated by tools/versions.py: the versions with a playable snapshot here.\n')
        f.write('window.SNAPSHOTS = ' + json.dumps({str(v): last.get(v, ('', ''))[0][:7] for v in have}) + ';\n')
    print(f'{len(have)} snapshots: v{have[0]} to v{have[-1]}')


if __name__ == '__main__':
    main()
